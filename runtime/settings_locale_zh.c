volatile int settings_zh_used;  // (set once Chinese is shown: the overlay then loads a font with its glyphs)

const char *settings_text_zh(const char *english) {
    settings_zh_used = 1;
    size_t lo = 0, hi = sizeof ZH / sizeof *ZH;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        int c = strcmp(english, ZH[mid].en);
        if (!c) return ZH[mid].zh;
        if (c < 0) hi = mid;
        else lo = mid + 1;
    }
    return english;  // (not translated yet: English)
}
